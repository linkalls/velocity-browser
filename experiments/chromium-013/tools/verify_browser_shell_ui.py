#!/usr/bin/env python3
"""Assert that Chrome/Vivaldi-inspired screens render real Android UI nodes.

No OCR or mocked screenshot data. Screens are generated by an isolated debug
Chromium APK with blank navigation; no credentials, tabs or URLs are exported.
"""
import argparse
import re
from pathlib import Path
import xml.etree.ElementTree as ET


def verify(path: Path, mode: str) -> None:
    root = ET.parse(path).getroot()
    nodes = list(root.iter('node'))
    text = {node.get('text', '') for node in nodes}
    desc = {node.get('content-desc', '') for node in nodes}
    visible = text | desc
    def require(*labels: str) -> None:
        for label in labels:
            assert label in visible, f'{mode}: missing visible UI label {label!r}'

    if mode == 'home':
        require('Velocity', 'Browse your way', 'ショートカットを追加',
                'Yahoo!ニュース ショートカット', '検索またはURLを入力')
    elif mode == 'menu':
        require('Velocity', '進む', '更新', '新規', '共有', 'ホーム', 'タブ一覧')
        require('新しい非公開タブ', 'ページ内検索', 'ダウンロード')
    elif mode.startswith('settings'):
        require('設定', '設定を閉じる')
        if mode == 'settings':
            require('外観', 'アドレスバーを下に配置', 'ショートカットを表示')
        elif mode == 'settings-tabs':
            require('タブ', 'タブのプレビューを保存', '新しいタブで検索欄を選択')
        elif mode == 'settings-media':
            require('メディア', '他アプリの音声を優先', '動画と音声の自動再生')
    elif mode == 'top-bar':
        require('Velocity', '通常タブ一覧', 'ブラウザメニュー')
    else:
        raise ValueError(f'Unsupported UI screen: {mode}')
    if mode in ('home', 'top-bar'):
        fields = [n for n in nodes if n.get('class') == 'android.widget.EditText']
        assert fields, f'{mode}: missing address EditText'
        bounds = fields[0].get('bounds', '')
        match = re.fullmatch(r'\[(\d+),(\d+)\]\[(\d+),(\d+)\]', bounds)
        assert match, f'{mode}: invalid address field geometry: {bounds!r}'
        top = int(match.group(2))
        height = max(int(n.get('bounds', '[0,0][0,0]').split(',')[-1].rstrip(']'))
                     for n in nodes if n.get('bounds'))
        if mode == 'top-bar':
            assert top < height / 2, f'Top address bar incorrectly at y={top}'
        else:
            assert top > height / 2, f'Bottom address bar incorrectly at y={top}'
    clickable = sum(n.get('clickable') == 'true' for n in nodes)
    assert clickable >= 5, f'{mode}: insufficient interactive UI: {clickable}'
    print(f'PASS Chrome/Vivaldi shell: {mode}, nodes={len(nodes)}, controls={clickable}')


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('xml', type=Path)
    parser.add_argument('mode', choices=('home', 'menu', 'top-bar', 'settings',
                                         'settings-tabs', 'settings-media'))
    args = parser.parse_args()
    verify(args.xml, args.mode)
